from datetime import datetime, timezone
from typing import Any, Optional
from uuid import uuid4

from app.models.schemas import Evidence, TestResult
from app.verification.patch_comparator import PatchComparisonResult


class EvidenceLedger:
    """
    Stores verification evidence generated by test execution
    and static patch comparison.

    Distinguishes between controlled demonstration fixtures (which
    cannot establish runtime security) and real application dynamic tests.
    """

    def __init__(self) -> None:
        self._evidence: list[Evidence] = []

    def record(
        self,
        result: TestResult,
        category: str = "CONTROLLED_DEMONSTRATION",
        supports_verification: bool = False,
    ) -> Evidence:
        """Record evidence from a test execution."""
        evidence = Evidence(
            evidence_id=str(uuid4()),
            test_id=result.test_id,
            category=category,
            description=result.details,
            observed={
                "outcome": result.outcome,
                "passed": result.passed,
                "execution_time_ms": result.execution_time_ms,
                "error": result.error,
                "target_type": "CONTROLLED_FIXTURE",
                "target_provenance": "DEMO_FIXTURE",
                "submitted_source_executed": False,
                "source_runtime_match": False,
                "verification_scope": "Simulated demonstration fixture only",
            },
            supports_verification=supports_verification,
            timestamp=datetime.now(timezone.utc).isoformat(),
        )

        self._evidence.append(evidence)
        return evidence

    def record_local_app_test(self, result: Any) -> Evidence:
        """
        Record empirical evidence from a dynamic application test.
        """
        source_runtime_match = getattr(result, "source_runtime_match", False)
        baseline_exploitable = getattr(result, "baseline_exploitable", False)
        patch_blocks_payload = getattr(result, "patch_blocks_payload", False)
        functionality_intact = getattr(result, "functionality_intact", False)
        has_error = bool(getattr(result, "error", None))

        supports_verif = bool(
            result.passed
            and source_runtime_match
            and baseline_exploitable
            and patch_blocks_payload
            and functionality_intact
            and not has_error
        )

        observed_payload = {
            "target_type": getattr(result, "target_type", "SUBMITTED_SOURCE_EXECUTION"),
            "target_provenance": getattr(result, "target_provenance", "RESTRICTED_SOURCE_ENV"),
            "submitted_source_executed": getattr(result, "submitted_source_executed", False),
            "source_runtime_match": source_runtime_match,
            "verification_scope": getattr(result, "verification_scope", "Targeted local SQLite user search query path"),
            "payload": getattr(result, "payload", ""),
            "outcome": result.outcome,
            "passed": result.passed,
            "baseline_exploitable": baseline_exploitable,
            "patch_blocks_payload": patch_blocks_payload,
            "functionality_intact": functionality_intact,
            "vulnerable_rows_count": len(getattr(result, "vulnerable_rows", [])),
            "patched_rows_count": len(getattr(result, "patched_rows", [])),
            "expected_behavior": getattr(result, "expected_behavior", ""),
            "observed_behavior": getattr(result, "observed_behavior", ""),
            "execution_time_ms": getattr(result, "execution_time_ms", None),
            "error": getattr(result, "error", None),
            "test_category": getattr(result, "category", None),
            "security_invariant": getattr(result, "security_invariant", None),
            "test_name": getattr(result, "test_name", None),
        }

        evidence = Evidence(
            evidence_id=str(uuid4()),
            test_id=result.test_id,
            category="REAL_APPLICATION_VERIFICATION",
            description=result.details,
            observed=observed_payload,
            supports_verification=supports_verif,
            timestamp=datetime.now(timezone.utc).isoformat(),
        )

        self._evidence.append(evidence)
        return evidence

    def record_patch_comparison(
        self,
        comparison: PatchComparisonResult,
    ) -> Evidence:
        """Record static original-versus-patched source comparison."""
        evidence = Evidence(
            evidence_id=str(uuid4()),
            test_id="STATIC_PATCH_COMPARISON",
            category="STATIC_ANALYSIS",
            description=comparison.summary,
            observed={
                "status": comparison.status,
                "original_rule_ids": comparison.original_rule_ids,
                "patched_rule_ids": comparison.patched_rule_ids,
                "static_improvement_detected": (
                    comparison.static_improvement_detected
                ),
                "dynamic_verification_performed": (
                    comparison.dynamic_verification_performed
                ),
                "target_type": "STATIC_SOURCE",
                "target_provenance": "SUBMITTED_SOURCE_AST",
                "submitted_source_executed": False,
                "source_runtime_match": True,
            },
            supports_verification=False,
            timestamp=datetime.now(timezone.utc).isoformat(),
        )

        self._evidence.append(evidence)
        return evidence

    def record_many(
        self,
        results: list[TestResult],
    ) -> list[Evidence]:
        return [self.record(result) for result in results]

    def get_all(self) -> list[Evidence]:
        return list(self._evidence)

    def clear(self) -> None:
        self._evidence.clear()
