from datetime import datetime, timezone
from uuid import uuid4

from app.models.schemas import Evidence, TestResult


class EvidenceLedger:
    """
    Stores verification evidence generated by test execution.

    Evidence from the current SQLite demonstration runner is
    explicitly marked as demonstration evidence.
    """

    def __init__(self) -> None:
        self._evidence: list[Evidence] = []

    def record(self, result: TestResult) -> Evidence:
        evidence = Evidence(
            evidence_id=str(uuid4()),
            test_id=result.test_id,
            category="CONTROLLED_DEMONSTRATION",
            description=result.details,
            observed={
                "outcome": result.outcome,
                "passed": result.passed,
                "execution_time_ms": result.execution_time_ms,
                "error": result.error,
            },
            supports_verification=False,
            timestamp=datetime.now(timezone.utc).isoformat(),
        )

        self._evidence.append(evidence)
        return evidence

    def record_many(
        self,
        results: list[TestResult],
    ) -> list[Evidence]:
        return [self.record(result) for result in results]

    def get_all(self) -> list[Evidence]:
        return list(self._evidence)

    def clear(self) -> None:
        self._evidence.clear()